    public void tampil() {
        Valid.tabelKosong(tabModeLocal);
        try {
            ps = koneksi.prepareStatement(
                    "select * "
                    + "from data_loinc where "
                    + "data_loinc.code like ? or data_loinc.component like ?  order by code ASC");
            try {
                ps.setString(1, "%" + TCari1.getText() + "%");
                ps.setString(2, "%" + TCari1.getText() + "%");
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabModeLocal.addRow(new Object[]{
                        rs.getString("code"), rs.getString("long_component"), rs.getString("component"),
                        rs.getString("property"), rs.getString("timing"), rs.getString("system"), rs.getString("scale"),
                        rs.getString("method")
                    });
                }
            } catch (Exception e) {
                System.out.println("Notif Loinc Data : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (Exception e) {
            System.out.println("Notifikasi : " + e);
        }
        LCount1.setText("" + tabModeLocal.getRowCount());
    }
