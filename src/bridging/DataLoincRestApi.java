    public void tampilListLoinc(String componen) {
        this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        String halaman, offset;
        halaman = page.getSelectedItem().toString();
        int next = hal.getSelectedIndex();
        offset = (Integer.parseInt(halaman) * next) + "";
        Valid.tabelKosong(tabMode);
        auth = userLoinc+":"+passLoinc;
        byte[] encodedBytes = Base64.encodeBase64(auth.getBytes());
        authEncrypt = new String(encodedBytes);
        try {
            int hasil, total, perpage;
            headers = new HttpHeaders();
            headers.setContentType(MediaType.APPLICATION_JSON);
            headers.add("Authorization", "Basic " + authEncrypt);
            requestEntity = new HttpEntity(headers);
            root = mapper.readTree(api.getRest().exchange("https://loinc.regenstrief.org/searchapi/loincs?query=" + componen + "&rows=" + halaman + "&offset=" + offset + "&sortorder=loinc_num", HttpMethod.GET, requestEntity, String.class).getBody());
            LCount.setText(root.path("ResponseSummary").path("RecordsFound").asText());
            for (JsonNode list : root.path("Results")) {
                tabMode.addRow(new String[]{
                    list.path("LOINC_NUM").asText(), list.path("LONG_COMMON_NAME").asText(), list.path("COMPONENT").asText(),
                    list.path("PROPERTY").asText(), list.path("TIME_ASPCT").asText(), list.path("SYSTEM").asText(),
                    list.path("SCALE_TYP").asText(), list.path("METHOD_TYP").asText(), list.path("EXAMPLE_UCUM_UNITS").asText()
                });
                i++;
            }
            j = 1;
            total = Integer.parseInt(root.path("ResponseSummary").path("RecordsFound").asText());
            perpage = Integer.parseInt(page.getSelectedItem().toString());
            hasil = total / perpage;
            hal.removeAllItems();
            for (j = 1; j <= hasil; j++) {
                combo = "false";
                hal.addItem(j);
            }
            combo = "true";
        } catch (Exception e) {
            System.out.println("Notifikasi : " + e);
        }
        this.setCursor(Cursor.getDefaultCursor());
    }

